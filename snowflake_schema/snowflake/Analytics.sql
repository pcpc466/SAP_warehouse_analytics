--1 What is the total sales?
SELECT 
    TO_VARCHAR(SUM(ITEM_NET_AMOUNT), '$999,999,999,999.99') AS TOTAL_SALES
FROM SAP_DB.ANALYTICS.FACT_SALES_ORDERS;

--2  Which product category has highest sale?
SELECT M.MATERIAL_GROUP, 
M.MATERIAL_DESCRIPTION, 
SUM(F.ITEM_NET_AMOUNT) AS TOTAL_SALES
FROM SAP_DB.ANALYTICS.FACT_SALES_ORDERS F 
LEFT JOIN SAP_DB.ANALYTICS.DIM_MATERIAL M 
ON F.PRODUCT_ID = M.MATERIAL_NUMBER
WHERE F.ITEM_NET_AMOUNT IS NOT NULL
GROUP BY 1,2
ORDER BY 3 DESC;


--3 Whats monnth over month sales look like?
WITH MONTHLY_SALES AS ( 
SELECT 
DATE_TRUNC('month', ORDER_DATE) AS SALES_MONTH, 
SUM(ITEM_NET_AMOUNT) AS TOTAL_SALES,
LAG(SUM(ITEM_NET_AMOUNT)) OVER (ORDER BY DATE_TRUNC('month', ORDER_DATE)) AS LAST_MONTH_SALES
FROM SAP_DB.ANALYTICS.FACT_SALES_ORDERS 
WHERE ORDER_DATE IS NOT NULL 
GROUP BY 1
) 

SELECT 
TO_VARCHAR(SALES_MONTH, 'YYYY-MM') AS MONTHL_OF_SALE,
TO_VARCHAR(TOTAL_SALES, '$999,999,999,999.99') AS CURRENT_SALES,
TO_VARCHAR(LAST_MONTH_SALES, '$999,999,999,999.99') AS PREVIOUS_SALES, 
ROUND((TOTAL_SALES - LAST_MONTH_SALES),2) MOM_DIFFERENCE, 
ROUND(((TOTAL_SALES - LAST_MONTH_SALES) / LAST_MONTH_SALES) * 100, 2) || '%' AS MOM_GROWTH_PERC
FROM MONTHLY_SALES
WHERE PREVIOUS_SALES IS NOT NULL -- As there were a few initial months with null sales.
ORDER BY MONTHL_OF_SALE DESC
LIMIT 100;

-- 4 What is fulfillmemnt rate ? -- ordershipped /orderplaced

SELECT COUNT(BILLING_ITEM) AS TOTAL_ORDER_PLACED, COUNT(
CASE WHEN IS_CANCELLED = 'X' THEN BILLING_ITEM END) AS CANCELLED_ORDER, 
ROUND(((TOTAL_ORDER_PLACED - CANCELLED_ORDER) / TOTAL_ORDER_PLACED) * 100,2) AS REPLENISHMENT_RATE
FROM ANALYTICS.FCT_BILLING_ITEM;

-- 5 What is match rate?

SELECT
    I.PO_NUMBER,
    I.PO_ITEM,
    PO.CHANGED_ON      AS PO_DATE,
    I.POSTING_DATE      AS INVOICE_DATE,
    DATEDIFF('day', PO.CHANGED_ON, I.POSTING_DATE) AS PRO2PAY_DAYS
FROM SAP_DB.ANALYTICS.FCT_AP_INVOICE_ITEM I
LEFT JOIN SAP_DB.ANALYTICS.FCT_PROCUREMENT_ITEM PO
    ON PO.PO_NUMBER = I.PO_NUMBER
   AND PO.PO_ITEM   = I.PO_ITEM
WHERE PO.CHANGED_ON IS NOT NULL
  AND DATEDIFF('day', PO.CHANGED_ON, I.POSTING_DATE) BETWEEN 0 AND 365  -- guard against bad-data outliers
ORDER BY INVOICE_DATE
LIMIT 100;

-- 6 What is the product with the highest profit margin?
-- had to use multiple joins as different vendors had the same material number. 

WITH product_margin AS (
    SELECT
        S.MATERIAL_NUMBER,
        M.MATERIAL_DESCRIPTION,
        ROUND(SUM(S.NET_AMOUNT),2)                           AS TOTAL_REVENUE,
        SUM(S.ORDER_QUANTITY)                          AS TOTAL_QUANTITY_SOLD,
        AVG(C.NET_PRICE)                               AS AVG_UNIT_COST,
        ROUND(SUM(S.ORDER_QUANTITY) * AVG(C.NET_PRICE))       AS TOTAL_COST,
        COUNT(DISTINCT S.SALES_DOC_ID)                 AS ORDER_COUNT
    FROM SAP_DB.ANALYTICS.FCT_SALES_ORDER_ITEM S
    JOIN SAP_DB.ANALYTICS.DIM_MATERIAL_CLEAN M
        ON S.MATERIAL_NUMBER = M.MATERIAL_NUMBER
    JOIN SAP_DB.ANALYTICS.FCT_PROCUREMENT_ITEM C
        ON S.MATERIAL_NUMBER = C.MATERIAL_NUMBER
       AND S.CURRENCY = C.CURRENCY
       WHERE M.MATERIAL_DESCRIPTION IS NOT NULL
    GROUP BY S.MATERIAL_NUMBER, M.MATERIAL_DESCRIPTION
)
SELECT
    MATERIAL_NUMBER,
    MATERIAL_DESCRIPTION,
    TOTAL_REVENUE,
    TOTAL_COST,
    ROUND((TOTAL_REVENUE - TOTAL_COST) / NULLIF(TOTAL_REVENUE, 0) * 100, 2) || '%' AS P_MARGIN_PCT,
    ORDER_COUNT
FROM product_margin
WHERE TOTAL_REVENUE > 0
ORDER BY P_MARGIN_PCT DESC
LIMIT 20;

-- 7. What is vendor concentration as (top 10 vendors)? (TOP10/ALL*100)

WITH TOP_VENDORS AS ( 
SELECT VENDOR_ID,
SUM(LINE_VALUE) AS VENDOR_COST
FROM ANALYTICS.FCT_PROCUREMENT_ITEM
WHERE VENDOR_ID IS NOT NULL 
AND VENDOR_ID NOT LIKE '%TEST' 
AND LINE_VALUE IS NOT NULL 
GROUP BY 1
ORDER BY 2 DESC
LIMIT 10
), 

TOTAL_COST AS ( 
SELECT SUM(LINE_VALUE) AS GRAND_COST
FROM ANALYTICS.FCT_PROCUREMENT_ITEM
) 

SELECT V.VENDOR_ID, 
V.VENDOR_COST,
ROUND ((V.VENDOR_COST/ C.GRAND_COST)* 100,2) || '%' AS PCT_OF_COST
FROM TOP_VENDORS V
JOIN TOTAL_COST C
ORDER BY PCT_OF_COST DESC
LIMIT 10;

-- 8. What is cancellation rate?

WITH CANCEL_COUNT AS (
SELECT  COUNT(BILLING_ITEM) AS TOTAL_BILLED, 
COUNT(CASE WHEN IS_CANCELLED = 'X' THEN 1 END) AS CANCELATION_COUNT
FROM ANALYTICS.FCT_BILLING_ITEM
)

SELECT TOTAL_BILLED, CANCELATION_COUNT,
(CANCELATION_COUNT/TOTAL_BILLED * 100 ) || '%' AS CANCELLATION_RATE
FROM CANCEL_COUNT;

