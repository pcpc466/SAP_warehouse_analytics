-- RECONCILIATION VIEWS

-- FACT ORDER AND BILLING

CREATE OR REPLACE VIEW ANALYTICS.VW_ORDER_VS_BILLING AS
SELECT
    O.SALES_DOC_ID, O.ITEM_NUMBER, O.MATERIAL_NUMBER, O.ORDER_QUANTITY,
    O.NET_AMOUNT AS ORDERED_AMOUNT, O.CURRENCY,
    COALESCE(SUM(B.BILLED_QUANTITY), 0) AS BILLED_QUANTITY,
    COALESCE(SUM(B.NET_AMOUNT), 0)      AS BILLED_AMOUNT,
    O.NET_AMOUNT - COALESCE(SUM(B.NET_AMOUNT), 0) AS OPEN_AMOUNT
FROM ANALYTICS.FCT_SALES_ORDER_ITEM O
LEFT JOIN ANALYTICS.FCT_BILLING_ITEM B
    ON O.SALES_DOC_ID = B.REF_SALES_DOC_ID AND O.ITEM_NUMBER = B.REF_SALES_ITEM
   AND B.IS_CANCELLED != 'X'
GROUP BY O.SALES_DOC_ID, O.ITEM_NUMBER, O.MATERIAL_NUMBER, O.ORDER_QUANTITY, O.NET_AMOUNT, O.CURRENCY;

-- FACT PROCUREMENT AND INVOICE 
CREATE OR REPLACE VIEW ANALYTICS.VW_PO_VS_INVOICE AS
SELECT
    P.PO_NUMBER, P.PO_ITEM, P.MATERIAL_NUMBER, P.PO_QUANTITY,
    P.LINE_VALUE AS PO_VALUE, P.CURRENCY,
    COALESCE(SUM(INV.ITEM_AMOUNT), 0) AS INVOICED_AMOUNT,
    P.LINE_VALUE - COALESCE(SUM(INV.ITEM_AMOUNT), 0) AS UNINVOICED_VALUE
FROM ANALYTICS.FCT_PROCUREMENT_ITEM P
LEFT JOIN ANALYTICS.FCT_AP_INVOICE_ITEM INV
    ON P.PO_NUMBER = INV.PO_NUMBER AND P.PO_ITEM = INV.PO_ITEM
GROUP BY P.PO_NUMBER, P.PO_ITEM, P.MATERIAL_NUMBER, P.PO_QUANTITY, P.LINE_VALUE, P.CURRENCY;

