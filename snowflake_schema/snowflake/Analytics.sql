-- DIM_DATE -- generated calendar 

CREATE OR REPLACE TABLE ANALYTICS.DIM_DATE AS
SELECT
    DATE_KEY,
    YEAR(DATE_KEY)        AS YEAR_NUM,
    QUARTER(DATE_KEY)     AS QUARTER_NUM,
    MONTH(DATE_KEY)       AS MONTH_NUM,
    MONTHNAME(DATE_KEY)   AS MONTH_NAME,
    DAY(DATE_KEY)         AS DAY_NUM,
    DAYNAME(DATE_KEY)     AS DAY_NAME,
    DAYOFWEEK(DATE_KEY)   AS DAY_OF_WEEK,
    WEEKOFYEAR(DATE_KEY)  AS WEEK_OF_YEAR,
    CASE WHEN DAYOFWEEK(DATE_KEY) IN (0,6) THEN TRUE ELSE FALSE END AS IS_WEEKEND
FROM (
    SELECT DATEADD(DAY, SEQ4(), '1994-01-01'::DATE) AS DATE_KEY -- 1994 is the first year while 2022 is the last year
    FROM TABLE(GENERATOR(ROWCOUNT => 13514))
);


